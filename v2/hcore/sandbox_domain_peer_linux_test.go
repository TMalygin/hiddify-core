// The engine, selection and broker are real. This fixture controls only the
// verified-peer feed from each transport: a failed handshake emits nothing.
type domainPeerSource struct {
	adapter.Outbound
	mu            sync.Mutex
	last          netip.AddrPort
	watch         chan netip.AddrPort
	onUnsubscribe netip.AddrPort
}

func (s *domainPeerSource) WatchVerifiedRealityPeer(replay bool) (<-chan netip.AddrPort, func()) {
	s.mu.Lock()
	defer s.mu.Unlock()
	ch := make(chan netip.AddrPort, 1)
	s.watch = ch
	if replay && s.last.IsValid() {
		ch <- s.last
	}
	return ch, func() {
		s.mu.Lock()
		defer s.mu.Unlock()
		if s.watch == ch {
			if s.onUnsubscribe.IsValid() {
				select {
				case <-ch:
				default:
				}
				ch <- s.onUnsubscribe
			}
			close(ch)
			s.watch = nil
		}
	}
}

func (s *domainPeerSource) record(peer netip.AddrPort) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.last = peer
	if s.watch != nil {
		select {
		case <-s.watch:
		default:
		}
		s.watch <- peer
	}
}

func (s *domainPeerSource) subscribed() bool {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.watch != nil
}

func domainPeerEngine(t *testing.T, opts option.Options) map[string]*domainPeerSource {
	t.Helper()
	ctx := libbox.BaseContext(nil)
	dir := t.TempDir()
	ctx = filemanager.WithDefault(ctx, dir, dir, os.Getuid(), os.Getgid())
	registry := service.FromContext[adapter.OutboundRegistry](ctx).(*outbound.Registry)
	sources := make(map[string]*domainPeerSource)
	outbound.Register(registry, "vless", func(ctx context.Context, r adapter.Router, l log.ContextLogger, tag string, o option.VLESSOutboundOptions) (adapter.Outbound, error) {
		live, err := vless.NewOutbound(ctx, r, l, tag, o)
		if err != nil {
			return nil, err
		}
		wrapped := &domainPeerSource{Outbound: live}
		sources[tag] = wrapped
		return wrapped, nil
	})
	box, err := NewService(ctx, opts, nil)
	require.NoError(t, err)
	previous := static.StartedService
	static.StartedService = box
	t.Cleanup(func() {
		sandboxBegin(context.Background())
		static.StartedService = previous
		require.NoError(t, closeService(box))
	})
	return sources
}

func TestSandboxDomainPeerLease(t *testing.T) {
	sandboxRealitySettings(t)
	a, b := sandboxRealityOptions(t), sandboxRealityOptions(t)
	a.Server, b.Server = "a.invalid", "b.invalid"
	a.ServerPort, b.ServerPort = 443, 7443
	b.TLS.ServerName = "other-reality.example"
	opts := option.Options{
		Experimental: &option.ExperimentalOptions{ClashAPI: &option.ClashAPIOptions{ExternalController: "127.0.0.1:0"}},
		Route:        &option.RouteOptions{Final: "first"},
		Outbounds: []option.Outbound{
			{Type: "vless", Tag: "a", Options: a}, {Type: "vless", Tag: "b", Options: b},
			{Type: "direct", Tag: "direct", Options: &option.DirectOutboundOptions{}},
			{Type: "selector", Tag: "first", Options: &option.SelectorOutboundOptions{Outbounds: []string{"a"}}},
			{Type: "selector", Tag: "mutable", Options: &option.SelectorOutboundOptions{Outbounds: []string{"a", "b"}}},
		},
	}
	sources := domainPeerEngine(t, opts)
	first, second := sources["a"], sources["b"]
	require.NotNil(t, first)
	require.NotNil(t, second)
	publish := func(tag string) {
		c := opts
		c.Route = &option.RouteOptions{Final: tag}
		sandboxPublish(sandboxBegin(context.Background()), &c)
	}
	policy := func() *sandbox.Policy {
		sandboxLeases.Lock()
		defer sandboxLeases.Unlock()
		return sandboxLeases.policy
	}
	until := func(f func() bool, why string) {
		t.Helper()
		require.Eventually(t, f, time.Second, 2*time.Millisecond, why)
	}
	offline := func(why string) {
		t.Helper()
		require.Never(t, func() bool { return policy() != nil }, 35*time.Millisecond, 2*time.Millisecond, why)
	}
	addrA := netip.MustParseAddrPort("192.0.2.31:443")
	addrB := netip.MustParseAddrPort("[2001:db8::32]:7443")
	publish("first")
	offline("a domain without an authenticated observation cannot be dialled on behalf of a managed application")
	// No transport evidence is generated by failed auth or by another leaf.
	second.record(addrB)
	offline("traffic authenticated by an unselected outbound is not permission")
	until(first.subscribed, "subscribe to the actual selected runtime instance without dialing")
	require.False(t, second.subscribed())
	for _, bad := range []string{"192.0.2.31:444", "0.0.0.0:443", "224.0.0.1:443", "[fe80::1%lo]:443", "[::ffff:169.254.1.1]:443"} {
		first.record(netip.MustParseAddrPort(bad))
		offline("an unusable physical peer cannot produce a worker policy")
	}
	first.record(addrA)
	until(func() bool { v := policy(); return v != nil && v.Server == addrA.Addr().String() }, "this instance's verified IP must authorize the numeric worker")
	expected := *a
	expected.Server = addrA.Addr().String()
	want, err := sandboxLeaf(option.Outbound{Type: "vless", Tag: "a", Options: &expected})
	require.NoError(t, err)
	require.Equal(t, want, policy(), "the pinned policy preserves port, UUID, SNI, public key, short ID, DNS and transport options")
	require.Equal(t, "a.invalid", a.Server, "keep the ordinary engine's hostname")
	revision := func() uint64 { sandboxLeases.Lock(); defer sandboxLeases.Unlock(); return sandboxLeases.revision }
	allowed := revision()
	first.record(addrA)
	require.Never(t, func() bool { return revision() != allowed }, 55*time.Millisecond, 2*time.Millisecond, "duplicate physical confirmation must not restart a worker or retry one that failed")
	other := netip.MustParseAddrPort("192.0.2.99:443")
	first.record(other)
	until(func() bool { v := policy(); return v != nil && v.Server == other.Addr().String() }, "a newly authenticated address replaces the old numeric endpoint")
	require.Equal(t, a.TLS.Reality.PublicKey, policy().PublicKey)
	first.record(netip.MustParseAddrPort("192.0.2.31:444"))
	until(func() bool { return policy() == nil }, "new unusable evidence revokes a formerly valid lease")
	first.record(addrA)
	until(func() bool { return policy() != nil }, "the next valid observation restores the same live leaf")
	first.mu.Lock()
	first.onUnsubscribe = addrA
	first.mu.Unlock()
	publish("b")
	until(second.subscribed, "watch the newly selected B")
	offline("B's cached verification from before the selection is stale")
	second.record(addrB)
	until(func() bool { v := policy(); return v != nil && v.Server == addrB.Addr().String() }, "use the first fresh confirmation from B")
	require.False(t, first.subscribed())
	require.Equal(t, b.TLS.ServerName, policy().ServerName)
	require.Equal(t, b.TLS.Reality.PublicKey, policy().PublicKey)
	require.Equal(t, b.ServerPort, policy().ServerPort)
	first.record(netip.MustParseAddrPort("192.0.2.33:443"))
	require.Never(t, func() bool { v := policy(); return v == nil || v.Server != addrB.Addr().String() }, 35*time.Millisecond, 2*time.Millisecond, "late or queued events from A must never replace B")
	for _, tag := range []string{"direct", "mutable"} {
		publish(tag)
		first.record(addrA)
		second.record(addrB)
		offline("DIRECT and an externally mutable selector cannot grant permission")
		require.False(t, first.subscribed())
		require.False(t, second.subscribed())
	}
	publish("a")
	until(first.subscribed, "watch A after A→B→DIRECT→A")
	offline("the same still-live A must authenticate again after a revoked period")
	first.record(addrA)
	until(func() bool { v := policy(); return v != nil && v.Server == addrA.Addr().String() }, "a new authentication of the very same address on A reopens the lease")
	finish := sandboxSelection()
	offline("a pending selection revokes an existing permission")
	finish(true)
	until(first.subscribed, "a successful re-selection reinstalls a fresh-only watch")
	offline("reselection cannot reauthorize A using a cached witness")
	first.record(addrA)
	until(func() bool { return policy() != nil }, "a new handshake after reselection authorizes A")
	publish("b")
	until(second.subscribed, "watch B after the reload")
	offline("hot reload retaining B must not reuse a past witness")
	second.record(addrB)
	until(func() bool { return policy() != nil }, "B can be reselected")
	sandboxBegin(context.Background())
	second.record(addrB)
	offline("stop invalidates a queued observation and permission")
	require.False(t, second.subscribed())
	replacement := domainPeerEngine(t, opts)
	replacement["b"].record(addrB)
	publish("b")
	until(func() bool { v := policy(); return v != nil && v.Server == addrB.Addr().String() }, "initial publication of a new runtime may replay its own authenticated pre-publication connection")
	extra := *b
	insecure := *b.TLS
	insecure.Insecure = true
	extra.TLS = &insecure
	bad := opts
	bad.Route = &option.RouteOptions{Final: "b"}
	bad.Outbounds = []option.Outbound{{Type: "vless", Tag: "b", Options: &extra}}
	sandboxPublish(sandboxBegin(context.Background()), &bad)
	replacement["b"].record(addrB)
	offline("a verified peer cannot authorize disallowed TLS options")
}
